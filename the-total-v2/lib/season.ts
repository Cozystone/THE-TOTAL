/*
 * 첫 시즌 — S.01 선택의 근거.
 *
 * ENTRY_EXAM_AT: 온라인 입학시험 시각. 사이트의 모든 카운트다운 · 일정 표기는 이 값 하나에서만 온다.
 *   - 확정된 시각만 넣는다. 형식: ISO 8601 + 한국 시간 오프셋. 예) '2026-11-14T10:00:00+09:00'
 *   - 코드 대신 배포 환경 변수 NEXT_PUBLIC_ENTRY_EXAM_AT 으로도 넣을 수 있다(같은 값 하나).
 *   - 비어 있거나 이미 지났으면 카운트다운 대신 '다음 입학 일정 준비 중' 을 보여준다.
 *   지금은 확정된 날짜가 없다 → null.
 */
export const ENTRY_EXAM_AT: string | null = process.env.NEXT_PUBLIC_ENTRY_EXAM_AT || null;

/** 설정값을 시각으로. 형식이 틀리면 없는 것으로 본다(거짓 카운트다운 방지). */
export function examTime(): number | null {
  if (!ENTRY_EXAM_AT) return null;
  const t = Date.parse(ENTRY_EXAM_AT);
  return Number.isFinite(t) ? t : null;
}

